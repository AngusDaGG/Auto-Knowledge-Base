"""Bounded public-page fallback; never imports browser profiles or cookies.

Approach reference (MIT):
https://github.com/ZY-ZhichaoYu/shared-video-transcriber/blob/main/server.py
Only ordinary share HTML and responses generated by normal page navigation are used.
"""

import json
import math
import os
from pathlib import Path
import re
import shutil
import subprocess
from time import perf_counter
from urllib.error import HTTPError
from urllib.parse import urlsplit
from urllib.request import HTTPRedirectHandler, Request, build_opener
import download_diagnostics as trace

ROOT = Path(__file__).resolve().parent
MOBILE_UA = (
    "Mozilla/5.0 (iPhone; CPU iPhone OS 16_0 like Mac OS X) "
    "AppleWebKit/605.1.15 Version/16.0 Mobile/15E148 Safari/604.1"
)
HEADERS = {"User-Agent": MOBILE_UA, "Referer": "https://www.douyin.com/"}
CDN_SUFFIXES = (
    "douyinvod.com", "douyinstatic.com", "bytecdn.cn", "bytecdntp.com",
    "ibytedtos.com", "bytefcdn.com", "byteimg.com",
)
# Exact hosts observed in ordinary Douyin metadata and verified through its CDN DNS chain.
CDN_HOSTS = {"v5-dy-ov-experiment.zjcdn.com", "v5-hl-mly-ov.zjcdn.com"}
MAX_HTML_BYTES = 2 * 1024 * 1024
MAX_MEDIA_BYTES = 512 * 1024 * 1024


class FallbackError(RuntimeError):
    def __init__(self, message, video_id="", category="UNKNOWN", stage=""):
        super().__init__(message)
        self.video_id = video_id
        self.category = category
        self.stage = stage


def supported_page(url):
    parsed = urlsplit(url)
    host = (parsed.hostname or "").lower()
    return (parsed.scheme in ("http", "https") and not parsed.username
            and not parsed.password and parsed.port in (None, 80, 443)
            and any(host == suffix or host.endswith("." + suffix)
                    for suffix in ("douyin.com", "iesdouyin.com")))


def supported_media(url):
    parsed = urlsplit(url)
    host = (parsed.hostname or "").lower()
    return (parsed.scheme in ("http", "https") and not parsed.username
            and not parsed.password and parsed.port in (None, 80, 443)
            and (host in CDN_HOSTS or any(host == suffix or host.endswith("." + suffix) for suffix in CDN_SUFFIXES)))


class CheckedRedirect(HTTPRedirectHandler):
    def __init__(self, allowed):
        super().__init__()
        self.allowed = allowed

    def redirect_request(self, request, response, code, message, headers, new_url):
        if not self.allowed(new_url):
            raise FallbackError("重新導向至不支援的來源，已停止")
        return super().redirect_request(request, response, code, message, headers, new_url)


def video_id_from(value):
    match = re.search(r"/(?:share/)?video/(\d+)", value)
    if not match:
        match = re.search(r"\[Douyin\]\s+(\d+):", value)
    return match.group(1) if match else ""


def should_fallback(error):
    reason = str(error).lower()
    return "403" in reason or "fresh cookies" in reason or "cookies are needed" in reason


def router_data(html):
    marker = html.find("window._ROUTER_DATA")
    if marker < 0:
        raise ValueError("未找到 window._ROUTER_DATA")
    start = html.find("{", marker)
    if start < 0:
        raise ValueError("_ROUTER_DATA 缺少 JSON 物件")
    # JSONDecoder handles quoted braces and trailing JavaScript without executing it.
    value, _ = json.JSONDecoder().raw_decode(html[start:])
    if not isinstance(value, dict):
        raise ValueError("_ROUTER_DATA 不是 JSON 物件")
    return value


def find_aweme(value, expected_id):
    if isinstance(value, dict):
        if (str(value.get("aweme_id", "")) == expected_id
                and isinstance(value.get("video"), dict)):
            return value
        for child in value.values():
            found = find_aweme(child, expected_id)
            if found:
                return found
    elif isinstance(value, list):
        for child in value:
            found = find_aweme(child, expected_id)
            if found:
                return found
    return None


def router_values(value, key):
    result = []
    if isinstance(value, dict):
        if key in value:
            result.append(value[key])
        for child in value.values():
            result.extend(router_values(child, key))
    elif isinstance(value, list):
        for child in value:
            result.extend(router_values(child, key))
    return result


def aweme_info(aweme, expected_id, method):
    if str(aweme.get("aweme_id", "")) != expected_id:
        raise FallbackError("影片資訊 ID 與目標影片不一致", expected_id)
    return {"id": expected_id, "title": aweme.get("desc"),
            "uploader": (aweme.get("author") or {}).get("nickname"),
            "video": aweme.get("video") or {}, "download_method": method}


def share_info(source, known_id=""):
    """Read the short link and, only if needed, one canonical mobile share page."""
    video_id = video_id_from(source) or known_id
    diagnostics = []
    opener = build_opener(CheckedRedirect(supported_page))
    pages = [source]
    for url in pages:
        started = perf_counter()
        try:
            with opener.open(Request(url, headers=HEADERS), timeout=20) as response:
                final_url = response.geturl()
                video_id = video_id_from(final_url) or video_id
                raw = response.read(MAX_HTML_BYTES + 1)
                trace.set_video_id(video_id)
                trace.event("share_resolution", "success", (perf_counter() - started) * 1000,
                            http_status=response.status, byte_count=len(raw), body_type=trace.response_kind(raw))
                diagnostics.append(f"HTTP {response.status}，{len(raw)} bytes")
                if len(raw) > MAX_HTML_BYTES:
                    raise ValueError("分享頁超過 2 MiB 限制")
                html = raw.decode(response.headers.get_content_charset() or "utf-8", "replace")
            try:
                data = router_data(html)
                spider = [value if isinstance(value, bool) else "non_boolean" for value in router_values(data, "isSpider")]
                diagnostics.append("isSpider=" + json.dumps(spider, ensure_ascii=False))
                if not video_id:
                    paths = [str(item) for item in router_values(data, "lastPath") if str(item).isdigit()]
                    video_id = paths[0] if paths else ""
                aweme = find_aweme(data, video_id) if video_id else None
                if aweme:
                    trace.event("metadata", "success", method="share-page")
                    return aweme_info(aweme, video_id, "share-page"), video_id, diagnostics
                trace.event("metadata", "not_available", method="share-page", reason_code="router_missing_target")
                diagnostics.append("_ROUTER_DATA 未提供目標影片資料")
            except (ValueError, json.JSONDecodeError) as error:
                diagnostics.append(str(error))
            canonical = f"https://www.iesdouyin.com/share/video/{video_id}/" if video_id else ""
            if canonical and len(pages) == 1 and urlsplit(final_url).path.rstrip("/") != urlsplit(canonical).path.rstrip("/"):
                pages.append(canonical)
        except (HTTPError, OSError, FallbackError, ValueError) as error:
            trace.event("share_resolution", "BLOCKED_PLATFORM" if trace.category(error) == "BLOCKED_PLATFORM" else "failed",
                        (perf_counter() - started) * 1000, error_type=type(error).__name__,
                        http_status=getattr(error, "code", None))
            diagnostics.append(trace.safe_reason(error))
            if trace.category(error) == "BLOCKED_PLATFORM":
                raise FallbackError("分享頁拒絕存取，停止此影片", video_id,
                                    "BLOCKED_PLATFORM", "share_resolution") from error
            break
    return None, video_id, diagnostics


def browser_runtime(video_id):
    node = Path(os.environ.get("AKB_NODE") or shutil.which("node") or "")
    module_override = os.environ.get("AKB_PLAYWRIGHT_MODULE")
    if not node.is_file():
        raise FallbackError("既有 Node／Playwright 不可用；未自動安裝瀏覽器或套件", video_id,
                            "LOCAL_BROWSER_ERROR", "page_load")
    if module_override:
        module = Path(module_override).expanduser().resolve()
    else:
        try:
            resolved = subprocess.run(
                [str(node), "--print", "require.resolve('playwright/package.json')"],
                cwd=ROOT, capture_output=True, text=True, encoding="utf-8", timeout=10,
            )
            module = Path(resolved.stdout.strip()).parent if resolved.returncode == 0 else Path("")
        except (OSError, subprocess.TimeoutExpired):
            module = Path("")
    if not (module / "package.json").is_file():
        raise FallbackError("既有 Node／Playwright 不可用；未自動安裝瀏覽器或套件", video_id,
                            "LOCAL_BROWSER_ERROR", "page_load")
    return node, module


def _trace_visible_observation(diagnostic):
    """Forward fixed observation fields only; never persist browser payloads or URLs."""
    timings = diagnostic.get("timings_ms")
    observation = timings.get("observation") if isinstance(timings, dict) else None
    observation = (observation if type(observation) in (int, float)
                   and math.isfinite(observation) and observation >= 0 else 0)
    counts = {key: diagnostic.get(key) for key in ("audio_resources", "active_players", "ready_players")}
    excluded = diagnostic.get("response_excluded")
    if isinstance(excluded, dict):
        counts.update({"response_excluded_" + key: excluded.get(key)
                       for key in ("frame", "target", "path", "mime", "status")})
    error_type = diagnostic.get("error_type")
    if isinstance(error_type, str) and error_type in {
            "Error", "TypeError", "ReferenceError", "SyntaxError", "RangeError", "TimeoutError",
            "TargetClosedError", "ProbeTimeout", "OtherError"}:
        counts["error_type"] = error_type
    failure_phase = diagnostic.get("failure_phase")
    if isinstance(failure_phase, str) and failure_phase in {"launch", "page_setup", "navigation", "observation"}:
        counts["source_kind"] = failure_phase
    trace.event("browser_observation", "observed", observation, method="visible-browser", **counts)
    players = diagnostic.get("ready_player_observations")
    if isinstance(players, list):
        for player in players:
            if isinstance(player, dict):
                trace.event("browser_player", "observed", method="visible-browser", **{
                    key: player.get(key) for key in
                    ("player_index", "current_src_kind", "paused", "muted", "duration_seconds")})


def visible_browser_info(source, video_id, profile_dir):
    """Observe the target's normal playback in our dedicated visible browser."""
    if not video_id.isdigit() or not supported_page(source):
        raise FallbackError("無法確認目標影片，未啟動可見瀏覽器", video_id, "NO_SUPPORTED_MEDIA", "metadata")
    node, module = browser_runtime(video_id)
    profile_dir = Path(profile_dir)
    profile_dir.mkdir(parents=True, exist_ok=True)
    try:
        result = subprocess.run(
            [str(node), str(ROOT / "visible_browser_probe.cjs"), str(module),
             f"https://www.douyin.com/video/{video_id}", video_id, str(profile_dir.resolve())],
            capture_output=True, text=True, encoding="utf-8", timeout=75,
        )
        payload = json.loads(result.stdout)
        if not isinstance(payload, dict):
            raise ValueError("invalid probe result")
    except (OSError, subprocess.TimeoutExpired, ValueError) as error:
        trace.event("page_load", "failed", method="visible-browser", error_type=type(error).__name__)
        raise FallbackError("可見瀏覽器未能完成載入", video_id, "LOCAL_BROWSER_ERROR", "page_load") from error
    diagnostic = payload.get("diagnostics") or {}
    timings = diagnostic.get("timings_ms") or {}
    trace.set_video_id(video_id)
    trace.event("page_load", "success" if diagnostic.get("navigation_status") == 200 else "failed",
                timings.get("navigation", 0), method="visible-browser",
                http_status=diagnostic.get("navigation_status"), browser_closed=diagnostic.get("browser_closed"))
    _trace_visible_observation(diagnostic)
    if result.returncode or not payload.get("ok"):
        category = payload.get("category", "LOCAL_BROWSER_ERROR")
        trace.event("metadata", "BLOCKED_PLATFORM" if category == "BLOCKED_PLATFORM" else "not_available",
                    method="visible-browser", reason_code=payload.get("reason", "probe_failed"))
        error = FallbackError("可見瀏覽器：" + trace.safe_reason(payload.get("reason", "未取得播放音訊")),
                              video_id, category, "metadata")
        error.diagnostics = diagnostic
        raise error
    info = payload.get("info") or {}
    duration = info.get("expected_duration")
    if (str(info.get("id", "")) != video_id or not isinstance(duration, (int, float))
            or not math.isfinite(duration) or duration <= 0):
        raise FallbackError("可見瀏覽器影片 ID／長度無法確認", video_id, "INVALID_TARGET", "metadata")
    info["download_method"] = "visible-browser"
    trace.event("metadata", "success", method="visible-browser")
    return info


def browser_info(video_id):
    if not video_id.isdigit():
        raise FallbackError("無法確認影片 ID，未啟動瀏覽器")
    node, module = browser_runtime(video_id)
    try:
        result = subprocess.run(
            [str(node), str(ROOT / "browser_probe.cjs"), str(module),
             f"https://www.douyin.com/video/{video_id}", video_id],
            capture_output=True, text=True, encoding="utf-8", timeout=55,
        )
        payload = json.loads(result.stdout)
    except (OSError, subprocess.TimeoutExpired, ValueError) as error:
        trace.event("page_load", "failed", error_type=type(error).__name__)
        raise FallbackError(f"Playwright 執行失敗：{type(error).__name__}", video_id, "LOCAL_BROWSER_ERROR", "page_load") from error
    trace.set_video_id(video_id)
    diagnostic = payload.get("diagnostics") or {}
    timings = diagnostic.get("timings_ms") or {}
    navigation_status = diagnostic.get("navigation_status")
    trace.event("page_load", "success" if navigation_status == 200 else "failed", timings.get("navigation", 0),
                http_status=navigation_status, browser_closed=diagnostic.get("browser_closed"))
    for response in diagnostic.get("detail_responses", []):
        denied = response.get("access_denied") or response.get("status") in (401, 403, 429)
        trace.event("metadata", "BLOCKED_PLATFORM" if denied else (
            "success" if response.get("target_found") else "not_available"), response.get("elapsed_ms", 0),
                    http_status=response.get("status"), body_type=response.get("body_type"),
                    api_type="aweme_detail", argus_kind=response.get("argus_kind"),
                    byte_count=response.get("byte_count"), api_status=response.get("status_code"))
    if not diagnostic.get("detail_responses"):
        trace.event("metadata", "not_available", timings.get("metadata", 0), api_type="aweme_detail")
    if payload.get("category") == "BLOCKED_PLATFORM":
        trace.event("metadata", "BLOCKED_PLATFORM", timings.get("metadata", 0), reason_code="browser_access_denied")
    if result.returncode or not payload.get("ok"):
        raise FallbackError("Playwright：" + payload.get("reason", "未取得目標影片資訊")
                            + "；" + json.dumps(diagnostic, ensure_ascii=False), video_id,
                            payload.get("category", "UNKNOWN"), "metadata")
    return aweme_info(payload["aweme"], video_id, "playwright")


def urls_in(value):
    urls = []
    if isinstance(value, str):
        urls = [value]
    elif isinstance(value, list):
        for child in value:
            urls.extend(urls_in(child))
    elif isinstance(value, dict):
        for key in ("main_url", "backup_url", "url_list", "fallback_url"):
            urls.extend(urls_in(value.get(key)))
    return list(dict.fromkeys(url for url in urls if supported_media(url)))


def media_candidates(video):
    """Prefer the original audio, then low-bitrate progressive MP4 with sound.

    music.play_url is intentionally excluded: it can be background music only.
    DASH video-only representations are also excluded.
    """
    audio, progressive = [], []
    for item in video.get("bit_rate_audio") or []:
        meta = item.get("audio_meta") or {}
        audio.append((meta.get("bitrate") or 0, urls_in(meta.get("url_list"))))
    for key in ("play_url", "play_addr"):
        audio.append((0, urls_in((video.get("audio") or {}).get(key))))
    for item in video.get("bit_rate") or []:
        if item.get("format") == "mp4":
            progressive.append((item.get("bit_rate") or 0, urls_in(item.get("play_addr"))))
    result = []
    for _, urls in sorted(audio, key=lambda item: item[0]) + sorted(progressive, key=lambda item: item[0]):
        result.extend(urls)
    result.extend(urls_in(video.get("play_addr")))
    return list(dict.fromkeys(result))


def media_source_summary(video):
    """Count schema paths and accepted URLs without returning hostnames or URL values."""
    def strings(value):
        if isinstance(value, str):
            return [value]
        if isinstance(value, list):
            return [url for item in value for url in strings(item)]
        if isinstance(value, dict):
            return [url for key in ("main_url", "backup_url", "url_list", "fallback_url")
                    for url in strings(value.get(key))]
        return []
    sources = [("play_addr", video.get("play_addr"))]
    for key in ("play_url", "play_addr"):
        sources.append(("audio_" + key, (video.get("audio") or {}).get(key)))
    for item in video.get("bit_rate_audio") or []:
        sources.append(("audio_meta", (item.get("audio_meta") or {}).get("url_list")))
    for item in video.get("bit_rate") or []:
        kind = item.get("format")
        kind = kind if kind in ("mp4", "dash") else "missing_format" if kind is None else "other"
        sources.append(("bit_rate_" + kind, item.get("play_addr")))
    return [{"source_kind": kind, "url_count": len(strings(value)),
             "candidate_count": len(urls_in(value))} for kind, value in sources]


def validate_media(path, expected_duration=None):
    # PyAV is already required by faster-whisper; no extra production dependency.
    with trace.stage("audio_processing"):
        import av
        with av.open(str(path)) as container:
            if not container.streams.audio:
                raise FallbackError("媒體沒有音軌，未交給辨識模型")
            if not any(True for _ in container.decode(audio=0)):
                raise FallbackError("媒體音軌不可解碼或沒有音訊內容")
            if expected_duration is not None:
                duration = container.duration / av.time_base if container.duration is not None else None
                if (duration is None or not math.isfinite(duration)
                        or abs(duration - expected_duration) > max(3, expected_duration * 0.02)):
                    raise FallbackError("音訊長度與目標播放器不符，拒絕轉錄", category="INVALID_TARGET",
                                        stage="audio_processing")


def download_media(info, directory):
    trace.set_video_id(info["id"])
    started = perf_counter()
    urls = media_candidates(info.get("video") or {})
    for summary in media_source_summary(info.get("video") or {}):
        trace.event("media_url", "source_scan", **summary)
    trace.event("media_url", "success" if urls else "not_available", (perf_counter() - started) * 1000,
                candidate_count=len(urls), method=info["download_method"])
    if not urls:
        raise FallbackError("沒有符合目前格式及來源限制的媒體網址（尚未判定是否可公開下載）",
                            info["id"], "NO_SUPPORTED_MEDIA", "media_url")
    # One request per path. Never retry a denied CDN URL or alter its signature.
    target = directory / f"{info['download_method']}_media.bin"
    partial = target.with_suffix(".part")
    opener = build_opener(CheckedRedirect(supported_media))
    size = 0
    downloaded = False
    started = perf_counter()
    try:
        with opener.open(Request(urls[0], headers=HEADERS), timeout=20) as response:
            if response.status != 200:
                raise FallbackError(f"CDN HTTP {response.status}", info["id"])
            declared = response.headers.get("Content-Length")
            declared = int(declared) if declared else None
            if declared is not None and declared > MAX_MEDIA_BYTES:
                raise FallbackError("媒體超過 512 MiB 限制", info["id"])
            with partial.open("wb") as output:
                while chunk := response.read(256 * 1024):
                    size += len(chunk)
                    if size > MAX_MEDIA_BYTES:
                        raise FallbackError("媒體超過 512 MiB 限制", info["id"])
                    output.write(chunk)
            if size == 0 or (declared is not None and size != declared):
                raise FallbackError("CDN 媒體空白或下載不完整", info["id"])
        downloaded = True
        trace.event("media_download", "success", (perf_counter() - started) * 1000,
                    http_status=200, byte_count=size)
        if "expected_duration" in info:
            validate_media(partial, expected_duration=info["expected_duration"])
        else:
            validate_media(partial)
        partial.replace(target)
        info["download_bytes"] = size
        return target
    except Exception as error:
        if not downloaded:
            trace.event("media_download", "BLOCKED_PLATFORM" if trace.category(error) == "BLOCKED_PLATFORM" else "failed",
                        (perf_counter() - started) * 1000, http_status=getattr(error, "code", None),
                        byte_count=size, error_type=type(error).__name__)
        if partial.exists():
            partial.unlink()
        raise
